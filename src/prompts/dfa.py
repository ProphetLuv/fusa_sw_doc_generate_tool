# -*- coding: utf-8 -*-
"""DFA - 相关失效分析 Prompt（CCF + 级联 + 单点 + FFI）"""

from prompts._base import get_asil_requirements


def build_dfa_prompt(code: str, module_name: str, asil_level: str) -> str:
    """构建 DFA 文档生成 Prompt。"""
    asil_req = get_asil_requirements(asil_level)
    ffi_extra = ""
    if asil_level in ("ASIL C", "ASIL D"):
        ffi_extra = """
### 5.4 独立性论证（ASIL C/D 必需）
- 对每对安全相关元素提供形式化的独立性论证
- 论证方法：设计审查 + 数据流分析 + 控制流分析
- 若独立性不满足，必须给出补偿措施或架构重构建议"""

    return f"""你是一名功能安全工程师，请根据以下 C/C++ 嵌入式代码，执行完整的**相关失效分析（DFA, Dependent Failure Analysis）**，符合 ISO 26262:2018 Part 9 第 7 章（相关失效分析）和 Part 6 软件架构要求。

DFA 的目标是验证安全机制之间的独立性，识别可能导致安全目标同时失效的相关失效原因，包括：
- **共因失效（CCF）**：单一根本原因导致多个元素同时失效
- **级联失效（Cascading）**：一个元素的失效触发另一个元素失效
- **单点失效（SPF）**：无冗余/无检测的单一失效即可违反安全目标
- **独立性/无干扰分析（FFI）**：验证元素间不存在干扰路径

## 模块名称
{module_name}

## ASIL 等级
{asil_level}

## 本 ASIL 等级的 ISO 26262 Part 6 方法要求
{asil_req}

## 源代码
```c
{code}
```

## 输出格式要求

请按照以下结构输出 Markdown 格式的 DFA 报告：

# {module_name} 相关失效分析（DFA）

## 1. 分析范围与方法
- 分析目的：验证安全机制独立性，识别相关失效风险
- 分析标准：ISO 26262:2018 Part 9 Clause 7
- 分析对象：从架构分解中识别的安全相关元素（引用 SAD 模块列表）
- 输入依据：架构设计（SAD）+ 已识别失效模式（FMEA）
- 分析方法：归纳法（自底向上）+ 演绎法（自顶向下）组合

## 2. 架构元素识别

从 SAD 架构分解中提取参与 DFA 分析的元素：

| 元素ID | 元素名称 | 元素类型 | ASIL等级 | 安全功能 | 来源(SAD章节) |
|--------|---------|---------|---------|---------|---------------|

元素类型：软件模块 / 硬件资源 / 通信通道 / 数据对象 / 安全机制

## 3. 共因失效分析（CCF）

### 3.1 CCF 触发因素识别

| CCF-ID | 触发因素 | 受影响元素 | 失效机制 | 可能性 | 严重度 | 风险等级 | 现有防御措施 | 建议措施 |
|--------|---------|-----------|---------|--------|--------|---------|------------|----------|

### 3.2 CCF 分析维度
请从以下维度逐一分析：
- **共享资源**：共用时钟、电源、内存区域、总线
- **共享数据**：全局变量、共享缓冲区、配置参数
- **环境因素**：温度、EMI、振动对多元素的共同影响
- **设计缺陷**：相同算法/库的共模失效
- **工具链因素**：相同编译器、代码生成器、静态分析工具引入的系统性缺陷
- **人为因素**：相同开发者/团队的系统性设计错误

## 4. 级联失效分析（Cascading）

### 4.1 级联路径识别

| 级联ID | 源元素 | 源失效模式(引用FMEA) | 传播路径 | 目标元素 | 目标失效影响 | 传播概率 | 检测机制 | 缓解措施 |
|--------|--------|-------------------|---------|---------|------------|---------|---------|----------|

### 4.2 级联失效传播图
使用 Mermaid 绘制级联失效传播路径图，标注传播条件和概率。

### 4.3 级联失效分析要点
- 接口传播：通过函数调用、参数传递、返回值
- 数据传播：通过共享变量、消息队列、DMA
- 资源传播：通过共享内存、CPU时间、外设
- 时序传播：通过中断延迟、调度优先级反转

## 5. 独立性/无干扰分析（FFI）

### 5.1 元素对独立性矩阵

| 元素A | 元素B | 交互类型 | 干扰路径 | 独立性判定 | 论证依据 | 补偿措施 |
|-------|-------|---------|---------|-----------|---------|----------|

独立性判定：✅独立 / ⚠️有条件独立 / ❌存在干扰

### 5.2 干扰路径详细分析
对每个判定为"❌存在干扰"或"⚠️有条件独立"的元素对，详细分析：
- 干扰类型（时间干扰 / 空间干扰 / 信息交换干扰）
- 干扰场景描述
- 影响的安全目标
- 现有隔离机制
- 补偿措施建议

### 5.3 FFI 设计原则验证
验证架构是否满足以下 FFI 设计原则：
- 时间隔离：任务调度是否有时间保护（时间分区/看门狗）
- 空间隔离：内存是否有空间保护（MPU/MMU/栈隔离）
- 信息交换隔离：通信是否有完整性校验（CRC/序列号/超时）
{ffi_extra}

## 6. 单点失效分析（SPF）

### 6.1 单点失效识别

| SPF-ID | 元素 | 失效模式 | 安全目标影响 | 是否有冗余 | 是否有检测 | 风险等级 | 改进建议 |
|--------|------|---------|------------|-----------|-----------|---------|----------|

### 6.2 单点失效度量
- 单点失效数量统计
- 单点失效覆盖率（有检测/冗余的 SPF 数量 / 总 SPF 数量）
- 残余单点失效列表及风险评估

## 7. DFA 综合评估

### 7.1 风险汇总矩阵

| 分析类型 | 高风险项 | 中风险项 | 低风险项 | 残余风险 |
|---------|---------|---------|---------|----------|
| CCF | | | | |
| 级联失效 | | | | |
| SPF | | | | |
| FFI | | | | |

### 7.2 改进措施优先级
按风险等级排序列出所有建议改进措施。

### 7.3 追溯矩阵

| DFA发现ID | 关联FMEA失效模式ID | 关联SAD架构元素 | 关联安全需求(SRS) | 验证方法 | 状态 |
|-----------|-------------------|---------------|-----------------|---------|------|

## 8. 结论与建议
- DFA 分析结论（独立性是否充分论证）
- 残余风险可接受性论证
- 后续验证活动建议（测试/分析/审查）

请确保 DFA 分析充分引用架构分解（SAD）和已识别的失效模式（FMEA），所有发现都应可追溯到具体的架构元素和失效模式。"""
