# -*- coding: utf-8 -*-
"""SDD - 软件详细设计 Prompt（ASIL差异化）"""

from prompts._base import get_asil_requirements


def build_sdd_prompt(code: str, module_name: str, asil_level: str) -> str:
    """构建 SDD 文档生成 Prompt。"""
    asil_req = get_asil_requirements(asil_level)
    wcet_extra = ""
    if asil_level in ("ASIL C", "ASIL D"):
        wcet_extra = """
| WCET分析方法 | 使用的分析工具/方法（静态分析/测量法） |
| 栈使用分析 | 最坏情况栈深度估算方法及结果 |"""

    return f"""你是一名功能安全工程师，请根据以下 C/C++ 嵌入式代码，撰写符合 ISO 26262 / ASPICE 标准的**软件详细设计文档（SDD）**。

## 模块名称
{module_name}

## ASIL 等级
{asil_level}

## 本 ASIL 等级的 ISO 26262 Part 6 方法要求
{asil_req}

## 源代码
```c
{code}
```

## 输出格式要求

请按照以下结构输出 Markdown 格式的 SDD 文档：

# {module_name} 软件详细设计文档（SDD）

## 1. 设计概述
模块架构概览、设计约束、与其他模块的关系。

## 2. 接口设计

### 2.1 函数接口详细设计

对代码中的每个函数，按以下格式描述：

#### 函数名: `function_name`

| 属性 | 描述 |
|------|------|
| 函数签名 | 完整签名 |
| 功能描述 | 函数功能说明 |
| 前置条件 | 调用前必须满足的条件 |
| 后置条件 | 调用后保证的状态 |
| 输入参数 | 参数名、类型、范围、含义 |
| 输出参数 | 参数名、类型、范围、含义 |
| 返回值 | 返回值类型及含义 |
| WCET | 最坏情况执行时间估算 |
| 线程安全 | 是否线程安全及原因 |
| 可重入性 | 是否可重入及原因 |
| 副作用 | 对全局状态的影响 |
| 错误处理 | 异常情况处理方式 |
{wcet_extra}

### 2.2 外部接口
硬件寄存器访问、外设通信接口、OS/RTOS 接口等。

## 3. 状态机设计
如果代码中包含状态机逻辑，请绘制状态转换表和状态转换图（Mermaid 格式）。

| 当前状态 | 触发事件 | 转换动作 | 下一状态 | 条件 |
|---------|---------|---------|---------|------|

## 4. 数据流设计
描述数据在模块内部的流转路径，包括数据变换、缓存、过滤等。

## 5. 数据结构设计
列出所有关键数据结构（struct、enum、union），说明每个字段的用途和取值范围。

## 6. 算法设计
对核心算法进行描述，包括算法逻辑、复杂度分析、边界条件处理。

## 7. 资源使用
| 资源类型 | 使用量估算 | 说明 |
|---------|-----------|------|
| ROM (代码段) | | |
| RAM (数据段) | | |
| 栈空间 | | |
| 外设 | | |
| 中断 | | |

## 8. 安全设计
防御性编程措施、故障检测机制、安全状态转换策略。

## 9. MISRA C 合规性说明
列出代码中已遵循的 MISRA C:2023 规则（区分 Mandatory/Required/Advisory 类别），以及任何偏差项和正式论证理由。

请确保设计文档与代码实现严格对应，每个设计元素都能追溯到具体代码。"""
