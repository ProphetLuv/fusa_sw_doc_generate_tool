# -*- coding: utf-8 -*-
"""TC-UNIT - 单元测试用例 Prompt（ASIL差异化 + SWE.4 增强 + 故障注入 + 双向追溯）"""

from prompts._base import get_asil_requirements, get_asil_coverage


def build_tc_unit_prompt(code: str, module_name: str, asil_level: str) -> str:
    """构建 TC-UNIT 文档生成 Prompt。"""
    asil_req = get_asil_requirements(asil_level)
    coverage_req = get_asil_coverage(asil_level)
    return f"""你是一名功能安全测试工程师，请根据以下 C/C++ 嵌入式代码，设计完整的**单元测试用例文档（TC-UNIT）**，符合 ISO 26262 Part 6 软件单元测试要求和 ASPICE SWE.4 单元测试规范。

## 模块名称
{module_name}

## ASIL 等级
{asil_level}

## 本 ASIL 等级的 ISO 26262 Part 6 方法要求
{asil_req}

## 源代码
```c
{code}
```

## 输出格式要求

请按照以下结构输出 Markdown 格式的单元测试用例文档：

# {module_name} 单元测试用例文档（TC-UNIT）

## 1. 测试策略
简述单元测试方法、覆盖目标、测试环境假设（含 Mock/Stub 策略）。
- **覆盖率目标**：{coverage_req}
- **测试框架**：Unity (C) / Google Test (C++)

## 2. 单元测试用例表

请使用以下五类测试设计技术，为代码中的每个函数设计单元测试用例：

### 2.1 等价类划分测试
针对输入参数的有效等价类和无效等价类设计用例。

### 2.2 边界值分析测试
针对参数取值边界（最小值、最小值+1、最大值-1、最大值、越界值）设计用例。

### 2.3 错误猜测测试
基于经验猜测可能的错误场景（空指针、整数溢出、数组越界、除零等）。

### 2.4 状态转换测试
如果代码包含状态机，设计覆盖所有状态转换路径的测试用例。

### 2.5 安全机制测试
针对故障检测、安全机制转换、看门狗、冗余校验等安全机制设计单元测试。
每个安全机制测试用例须关联 FMEA 中对应的诊断覆盖率（DC），验证安全机制的有效性是否满足 DC 目标值。

### 2.6 故障注入测试（FMEA 导出）
**从前置 FMEA 文档中逐条导出故障注入用例**：
- 针对 FMEA 中每个高 RPN / 高严重度的失效模式，设计对应的故障注入测试
- 注入方式包括：变量卡滞（stuck-at）、信号丢失、数据损坏、时序违规、边界溢出、未初始化访问
- 验证故障检测机制能否在 FTTI 内检测到注入的故障并转入安全状态
- 如果前置文档中无 FMEA，则基于代码分析自行推导关键失效模式并标注

测试用例表格格式：

| 测试用例ID | 测试技术 | 被测函数 | 测试目的 | 前置条件 | 输入数据 | 预期结果 | 优先级 | 追溯SRS | 追溯FMEA |
|-----------|---------|---------|---------|---------|---------|---------|--------|--------|----------|

要求：
- **测试用例ID**：格式 UT-MOD-XXX（XXX为三位序号，必须连续）
- **优先级**：高(安全相关) / 中(功能正确性) / 低(边界/异常)
- **追溯SRS**：关联到 SRS 需求ID（格式 SRS-MOD-XXX），必须引用前置 SRS 文档中实际存在的需求编号
- **追溯FMEA**：关联到 FMEA 失效模式ID（格式 FM-MOD-XXX），故障注入类用例必填；若无前置 FMEA 则标注"N/A-自行推导"

## 3. 测试规程（Test Procedure）

为每个高优先级测试用例提供详细的执行步骤：

| 步骤编号 | 操作描述 | 预期观察 | 通过准则 |
|---------|---------|---------|---------|

## 4. 单元测试代码

请为关键测试用例生成 Unity（C语言）和 Google Test（C++）两种框架的单元测试代码：

### 4.1 Unity 框架测试代码
```c
#include "unity.h"
// ... 完整的 Unity 单元测试代码，含 setUp/tearDown
```

### 4.2 Google Test 框架测试代码
```cpp
#include <gtest/gtest.h>
// ... 完整的 GTest 单元测试代码
```

## 5. 测试覆盖矩阵
单元测试用例与函数的覆盖矩阵表，标注每个函数被哪些用例覆盖。

## 6. 测试结果记录模板

提供测试结果记录表格，供实际测试执行时填写：

| 测试用例ID | 执行日期 | 执行者 | 实际结果 | 通过/失败 | 备注/缺陷ID |
|-----------|---------|--------|---------|----------|------------|

## 7. 覆盖率分析报告模板

| 覆盖类型 | 目标 | 实际值 | 是否达标 | 未覆盖项说明 |
|---------|------|--------|---------|------------|
| 语句覆盖 | 100% | | | |
| 分支覆盖 | {coverage_req} | | | |
{"| MC/DC覆盖 | ≥90% | | | |" if asil_level == "ASIL D" else ""}

## 8. 测试通过准则
- 所有高优先级用例必须 100% 通过
- 覆盖率必须达到 {coverage_req}
- 所有失败用例必须有对应的缺陷记录和修复计划

请确保单元测试用例全面覆盖代码的所有分支和路径，特别关注安全相关的测试场景。"""
